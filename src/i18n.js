export const dictionaries = {
  'en-IN': Object.fromEntries(messagePairs.map(([english]) => [english, english])),
  'hi-IN': Object.fromEntries(messagePairs),
}

export function translate(message, language = 'en-IN', values = {}) {
  const source = typeof message === 'string' ? message : ''
  const dictionary = dictionaries[language] || dictionaries['en-IN']
  const englishSource = Object.entries(dictionaries['hi-IN'])
    .find(([, hindi]) => hindi === source)?.[0]
  const translated = dictionary[source] || dictionary[englishSource] || source
  return translated.replace(/\{(\w+)\}/g, (placeholder, key) => (
    Object.hasOwn(values, key) ? String(values[key]) : placeholder
  ))
}

const LanguageContext = createContext(null)

function getInitialLanguage() {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY)
    return saved === 'hi-IN' || saved === 'en-IN' ? saved : 'en-IN'
  } catch {
    return 'en-IN'
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage)
  const t = useCallback((message, values) => translate(message, language, values), [language])

  useEffect(() => {
    document.documentElement.lang = language === 'hi-IN' ? 'hi' : 'en'
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
    } catch (error) {
      console.error('Could not save the MedSafe language preference:', error.message)
    }
  }, [language])

  return createElement(LanguageContext.Provider, { value: { language, setLanguage, t } }, children)
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider.')
  return context
}
